import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { appendFileSync, copyFileSync, existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const LEGAL = ["LICENSE", "NOTICE.md", "THIRD_PARTY_NOTICES.md", "LICENSES"];
const sha256 = (file) => createHash("sha256").update(readFileSync(file)).digest("hex");

function git(root, args) {
  const result = spawnSync("git", args, { cwd: root, encoding: "utf8" });
  if (result.status !== 0) throw new Error(`git ${args[0]} failed: ${result.error?.message ?? result.stderr}`);
  return result.stdout.trim();
}

function candidate(root, expectedCommit) {
  const commit = git(root, ["rev-parse", "HEAD"]);
  if (!/^[a-f0-9]{40}$/.test(commit) || (expectedCommit && commit !== expectedCommit)) {
    throw new Error("Candidate commit does not match the requested workflow commit");
  }
  if (git(root, ["status", "--porcelain", "--untracked-files=all"])) {
    throw new Error("Candidate working tree contains tracked or untracked changes");
  }
  const manifest = JSON.parse(readFileSync(join(root, "apps/desktop/package.json"), "utf8"));
  const committed = JSON.parse(git(root, ["show", `${commit}:apps/desktop/package.json`]));
  if (!/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(manifest.version) || manifest.version !== committed.version) {
    throw new Error("Desktop version must match the committed candidate");
  }
  if (manifest.build?.productName !== "WcSdAi" || manifest.build?.publish !== null) {
    throw new Error("Team installers require WcSdAi branding and publish:null");
  }
  return { commit, version: manifest.version };
}

function copyRegularFile(from, to) {
  const entry = lstatSync(from);
  if (entry.isSymbolicLink()) throw new Error(`Refusing symlink in artifact inputs: ${basename(from)}`);
  if (entry.isFile() && entry.size > 0) {
    copyFileSync(from, to);
  } else {
    throw new Error(`Artifact input must be a nonempty regular file: ${basename(from)}`);
  }
}

function emptyOutput(path) {
  if (existsSync(path)) throw new Error("Artifact output already exists; refusing to mix candidates");
  mkdirSync(path, { recursive: true });
}

function finish(root, output, metadata) {
  const legalFiles = git(root, ["ls-files", "-z", "--", ...LEGAL]).split("\0").filter(Boolean);
  if (LEGAL.slice(0, 3).some((name) => !legalFiles.includes(name)) || !legalFiles.some((name) => name.startsWith("LICENSES/"))) {
    throw new Error("Required license notices must be tracked in the candidate");
  }
  for (const name of legalFiles) {
    const target = join(output, name);
    mkdirSync(join(target, ".."), { recursive: true });
    copyRegularFile(join(root, name), target);
  }
  writeFileSync(join(output, "BUILD-INFO.json"), `${JSON.stringify(metadata, null, 2)}\n`);
  writeFileSync(join(output, "BUILD-INFO.md"), [
    `# WcSdAi ${metadata.version} team build`, "",
    `- Commit: ${metadata.commit}`,
    `- Platform: ${metadata.platform}; architecture: ${metadata.arch}`,
    `- Installer: ${metadata.installer ?? "Source archive only"}`,
    `- Corresponding source: ${metadata.sourceFile}`,
    `- Source SHA-256: ${metadata.sourceSha256}`,
    `- Workflow run: ${metadata.runUrl ?? "Local fixture / no hosted run recorded"}`,
    "- This is an unsigned team artifact, not a signed public release.",
    "- No Developer ID, Windows publisher certificate, or Apple notarization was used.",
    "- Automatic update publishing is disabled; install later team builds manually.",
    "- Keep OS security protections enabled. Trust and install only a candidate your team has verified.",
    "- SHA256SUMS verifies file integrity; it is not a publisher identity signature.",
    "- Installation acceptance must be checked on each target platform.", "",
    "The source archive is generated by git archive from the commit above. It includes",
    "the lockfiles, build scripts, license notices and build instructions. See README.md",
    "and scripts/README.md inside the archive. Third-party source obligations and asset",
    "rights remain subject to the repository licensing checklist.", "",
  ].join("\n"));
  const files = [];
  function visit(dir, prefix = "") {
    for (const name of readdirSync(dir).sort()) {
      const relative = prefix + name;
      if (lstatSync(join(dir, name)).isDirectory()) visit(join(dir, name), `${relative}/`);
      else files.push(`${sha256(join(dir, name))}  ${relative}`);
    }
  }
  visit(output);
  writeFileSync(join(output, "SHA256SUMS"), `${files.join("\n")}\n`);
}

export function packageSource({ root = ROOT, output, expectedCommit, runUrl }) {
  const info = candidate(root, expectedCommit);
  const artifactName = `WcSdAi-${info.version}-source-${info.commit.slice(0, 12)}`;
  const sourceFile = `${artifactName}.tar.gz`;
  emptyOutput(output);
  git(root, ["archive", "--format=tar.gz", `--prefix=${artifactName}/`, `--output=${join(output, sourceFile)}`, info.commit]);
  const metadata = { ...info, platform: "source", arch: "all", sourceFile, sourceSha256: sha256(join(output, sourceFile)), runUrl };
  finish(root, output, metadata);
  return { artifactName, output, version: info.version };
}

export function teamBuildPlan(platform, arch) {
  if (!((platform === "macos" && ["arm64", "x64"].includes(arch)) || (platform === "windows" && arch === "x64"))) {
    throw new Error("Unsupported team installer platform/architecture");
  }
  const script = platform === "macos" ? "dist:mac" : "dist:win";
  return ["--config.verify-deps-before-run=false", "--filter", "@pi-desktop/desktop", "run", script,
    // Existing dist entry points set --publish never exactly once. Repeating
    // it becomes an array in the builder parser, not the "never" policy.
    // publish:null remains the validated package value, not the CLI string "null".
    `--${arch}`, "-c.forceCodeSigning=false",
    ...(platform === "macos" ? ["-c.mac.identity=-", "-c.mac.notarize=false"] : ["-c.win.signExecutable=false"]),
  ];
}

export function buildTeamInstaller({ root = ROOT, platform, arch, nativePlatform = process.platform, nativeArch = process.arch, env = process.env, run = spawnSync }) {
  const args = teamBuildPlan(platform, arch);
  if (nativePlatform !== (platform === "macos" ? "darwin" : "win32") || nativeArch !== arch) {
    throw new Error("Team installers require a native runner matching the requested architecture");
  }
  candidate(root, env.GITHUB_SHA);
  const safeEnv = { ...env, CSC_IDENTITY_AUTO_DISCOVERY: "false" };
  for (const name of Object.keys(safeEnv)) {
    if (/^(?:CSC_|WIN_CSC_|APPLE_|AZURE_)/.test(name) && name !== "CSC_IDENTITY_AUTO_DISCOVERY") delete safeEnv[name];
  }
  // No publishing token reaches electron-builder; artifact uploads happen in Actions.
  delete safeEnv.GH_TOKEN;
  delete safeEnv.GITHUB_TOKEN;
  const result = run(nativePlatform === "win32" ? "pnpm.cmd" : "pnpm", args, {
    cwd: root, env: safeEnv, stdio: "inherit", shell: nativePlatform === "win32",
  });
  if (result.status !== 0) throw new Error(`Team installer build failed (${result.error?.message ?? result.signal ?? result.status})`);
}

export function packageInstaller({ root = ROOT, output, sourceDir, platform, arch, expectedCommit, runUrl }) {
  teamBuildPlan(platform, arch);
  const info = candidate(root, expectedCommit);
  const source = JSON.parse(readFileSync(join(sourceDir, "BUILD-INFO.json"), "utf8"));
  const sourceFile = `WcSdAi-${info.version}-source-${info.commit.slice(0, 12)}.tar.gz`;
  if (source.commit !== info.commit || source.version !== info.version || source.sourceFile !== sourceFile || source.sourceSha256 !== sha256(join(sourceDir, sourceFile))) {
    throw new Error("Source archive does not match the installer candidate or checksum");
  }
  const artifactName = `WcSdAi-${info.version}-${platform}-${arch}-unsigned`;
  const extension = platform === "macos" ? "dmg" : "exe";
  const sourceInstaller = platform === "macos" ? `WcSdAi-${info.version}-${arch}.dmg` : `WcSdAi-Setup-${info.version}.exe`;
  const installer = `${artifactName}.${extension}`;
  // Copy only explicitly named inputs, never release/**, logs, profiles or local config.
  const input = join(root, "apps/desktop/release", sourceInstaller);
  if (!existsSync(input)) throw new Error(`Required installer missing: ${sourceInstaller}`);
  emptyOutput(output);
  copyRegularFile(input, join(output, installer));
  copyRegularFile(join(sourceDir, sourceFile), join(output, sourceFile));
  finish(root, output, { ...info, platform, arch, installer, sourceFile, sourceSha256: source.sourceSha256, runUrl });
  return { artifactName, output, version: info.version };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [mode, platform, arch] = process.argv.slice(2);
  const runUrl = process.env.GITHUB_SERVER_URL && process.env.GITHUB_REPOSITORY && process.env.GITHUB_RUN_ID
    ? `${process.env.GITHUB_SERVER_URL}/${process.env.GITHUB_REPOSITORY}/actions/runs/${process.env.GITHUB_RUN_ID}` : undefined;
  const artifactRoot = process.env.RUNNER_TEMP ? join(process.env.RUNNER_TEMP, "wcsdai-team") : join(ROOT, ".artifacts/team");
  let result;
  if (mode === "source") result = packageSource({ output: join(artifactRoot, "source"), expectedCommit: process.env.GITHUB_SHA, runUrl });
  else if (mode === "build") buildTeamInstaller({ platform, arch });
  else if (mode === "installer") result = packageInstaller({ output: join(artifactRoot, "installer"), sourceDir: join(artifactRoot, "source-input"), platform, arch, expectedCommit: process.env.GITHUB_SHA, runUrl });
  else throw new Error("Usage: node scripts/team-installers.mjs source | build <macos|windows> <arm64|x64> | installer <macos|windows> <arm64|x64>");
  if (result && process.env.GITHUB_OUTPUT) {
    appendFileSync(process.env.GITHUB_OUTPUT, `artifact-name=${result.artifactName}\nartifact-path=${result.output}\nversion=${result.version}\n`);
  }
}
